package ua.fulla.catalogimport;

import static org.assertj.core.api.Assertions.assertThat;

import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;
import org.junit.jupiter.params.provider.ValueSource;

/** Examples of names and categories that pass and don't pass the clothing white list. */
class ClothingFilterTest {

    @ParameterizedTest
    @ValueSource(strings = {
        "Лляна сукня міді",
        "Джинси прямого крою",
        "Сукня-жакет коричневого кольору з рельєфами",
        "Футболка сіра з принтом",
        "Чоловіче темно-сіре поло",
        "Лонгслів з драпіюванням чорний",
        "Джемпер з вишивкою темно-зелений",
        "Гольф з високим горлом сірий",
        "Кардиган приталений коричневого кольору на ґудзиках",
        "Худі чорне",
        "Світшот оверсайз",
        "Жакет твід синій",
        "Куртка-бомбер з контрастним коміром темно-сірий",
        "Пуховик укорочений з капюшоном чорний",
        "Парка з капюшоном сірий",
        "Пальто оверсайз синього кольору з коміром стійка",
        "Тренч бежевий",
        "Штани палаццо сірий",
        "Шорти з екошкіри оливковий",
        "Спідниця міді чорного кольору оксамитова",
        "Комбінезон джинсовий",
        "Костюм чорного кольору з жакетом приталений і спідницею міді",
        "Сорочка бордового кольору з об'ємним рукавом і вишивкою",
        "Жилет вовняний",
        "Топ - корсет з мереживом чорний",
        "Сукня кремова",
        "Джинси прямого крою ззаду декоративна блискавка",
        "Linen midi dress",
    })
    void clothingNamesPass(String name) {
        assertThat(ClothingFilter.isClothing(name, null, null)).isTrue();
    }

    @ParameterizedTest
    @ValueSource(strings = {
        "Жіночі білі труси",
        "Жіноче тату",
        "Керамічна чашка",
        "Жіночий чорний бюстгальтер з мереживом",
        "Піжамний костюм з шортами",
        "Купальник суцільний чорний",
        "Шкарпетки молочного кольору у червоні зірочках",
        "Колготки 40 den",
        "Жіночі чорні шкіряні туфлі",
        "Поясна сумка біла",
        "Рюкзак міський",
        "Жіночий коричневий шкіряний гаманець",
        "Срібні сережки",
        "Намисто з перлів",
        "Ремінь шкіряний",
        "Шарф вовняний",
        "Бежева шапка",
        "Жіночий бордовий кашкет",
        "Рукавички шкіряні",
        "Блакитна керамічна тарілка 22 см",
        "Фіолетова свічка 15 см",
        "Віск для насипної свічки сірий, 200 г",
        "Ваза для квітів",
        "Плед вовняний",
        "Крем для рук",
        "Сертифікат на 1000 гривень",
        "Подарунковий сертифікат",
        "Скретч-карта",
        "Темний шоколад з вишнею та чебрецем",
        "Гребінець для одягу бежевий",
        "Чохол до мобільного телефону Apple iPhone чорний",
        // Clothing-like, but not on the white list: when unsure, don't import.
        "Корсет чорного кольору оксамитовий",
        "Боді з лого молочний",
        "Капелюх чорний",
        "LIMITED BLACK",
        "",
    })
    void otherNamesDontPass(String name) {
        assertThat(ClothingFilter.isClothing(name, null, null)).isFalse();
    }

    @ParameterizedTest(name = "{0} | {1} | {2} → {3}")
    @CsvSource(delimiter = '|', nullValues = "-", textBlock = """
        Чорна сукня                     | Жіночі сукні      | Товари для жінок > Одяг > Сукні та спідниці > Сукні             | true
        LIMITED                         | Жіночі худі       | Товари для жінок > Одяг > Кофти та піджаки > Худі               | true
        Модель 17                       | -                 | Товари для жінок > Одяг > Верхній одяг > Пальта                 | true
        Сорочка біла                    | -                 | Товари для жінок > Одяг                                         | true
        Чорний топ                      | Жіночі топи       | Товари для жінок > Білизна та домашній одяг > Білизна > Топи    | false
        Жіночий бордовий топ            | Жіночі топи       | Товари для жінок > Білизна та домашній одяг > Білизна > Топи    | false
        Труси LIMITED BLACK             | Жіночі труси      | Товари для жінок > Білизна та домашній одяг > Білизна > Трусики | false
        Жіноча нічна сорочка            | Жіночі нічні сорочки | Товари для жінок > Білизна та домашній одяг                  | false
        Чоловічі шкіряні черевики       | Чоловічі черевики | Товари для чоловіків > Взуття > Черевики                        | false
        Футболка з принтом              | Наліпка           | Дім та декор > Канцтовари > Паперова продукція > Наліпка        | false
        Футболка                        | -                 | Дім та декор > Декор для дому > Декор                           | false
        Боді чорне                      | Жіночі боді       | Товари для жінок > Одяг > Костюми та комбінезони > Боді         | false
        Хустка                          | Жіночі хустки     | Товари для жінок > Аксесуари > Шарфи та рукавички > Хустки      | false
        Жіночі білі труси               | -                 | -                                                               | false
        """)
    void productTypeAndCategoryDecideToo(String name, String productType, String category, boolean clothing) {
        assertThat(ClothingFilter.isClothing(name, productType, category)).isEqualTo(clothing);
    }
}
